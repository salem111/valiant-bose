interface I18nContextType {
  language: AppLanguage;
  setLanguage: (lang: AppLanguage) => void;
  t: (key: string) => string;
  dir: 'rtl' | 'ltr';
  currentOption: LanguageOption;
}

const I18nContext = createContext<I18nContextType>({
  language: 'ar',
  setLanguage: () => {},
  t: (key: string) => key,
  dir: 'rtl',
  currentOption: SUPPORTED_LANGUAGES[0],
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    const saved = localStorage.getItem('app_language');
    if (saved && (saved === 'ar' || saved === 'en' || saved === 'tr' || saved === 'fr')) {
      return saved as AppLanguage;
    }
    return 'ar';
  });

  const currentOption = SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0];

  const setLanguage = (lang: AppLanguage) => {
    setLanguageState(lang);
    localStorage.setItem('app_language', lang);
  };

  useEffect(() => {
    document.documentElement.dir = currentOption.dir;
    document.documentElement.lang = currentOption.code;
  }, [currentOption]);

  const t = (key: string): string => {
    return TRANSLATIONS[language]?.[key] || TRANSLATIONS.en?.[key] || TRANSLATIONS.ar?.[key] || key;
  };

  return (
    <I18nContext.Provider
      value={{
        language,
        setLanguage,
        t,
        dir: currentOption.dir,
        currentOption,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => useContext(I18nContext);
